def cm(z):
    """Απόσταση για το σχέδιο: cm ως 99 cm (π.χ. 31,5), αλλιώς m (π.χ. 1,485)."""
    z = abs(z)
    if z < 0.995:
        t = "%.1f" % (z * 100)
        return (t[:-2] if t.endswith(".0") else t).replace(".", ",")
    return ("%.3f" % z).rstrip("0").rstrip(".").replace(".", ",") + " m"


