def run_len(pts, upto=None):
    """Μήκος πολυγραμμής· upto = (x, y) σημείο πάνω της ως το οποίο μετράμε."""
    L = 0.0
    for (x0, y0), (x1, y1) in zip(pts, pts[1:]):
        d = math.hypot(x1 - x0, y1 - y0)
        if upto is not None:
            t = ((upto[0] - x0) * (x1 - x0) + (upto[1] - y0) * (y1 - y0)) / (d * d)
            if -1e-6 <= t <= 1 + 1e-6 and math.hypot(x0 + t * (x1 - x0) - upto[0], y0 + t * (y1 - y0) - upto[1]) < 0.02:
                return L + t * d
        L += d
    return L


def gr(z):
    return ("%+.2f" % z).replace(".", ",").replace("-", "−")


def lv_coll(pt=None):
    return HEAD - I_COLL * run_len(COLL, pt)


def lv_rain(pts, pt=None):
    return RAIN0 - I_RAIN * run_len(pts, pt)


