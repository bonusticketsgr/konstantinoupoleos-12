def _wall_at(M, pt):
    """Ο τοίχος που περιέχει το σημείο (ή, ως 6 cm, η παρειά στην οποία ανοίγεται αυλάκι)."""
    w = min(M.WALLS, key=lambda w_: CK.d_pt_poly(pt, w_["pts"])); d = CK.d_pt_poly(pt, w["pts"])
    return (w["id"].replace("T", "Τ").replace("A", "Α").replace("N", "Ν"), d) if d <= 0.06 else (None, d)


def _zone(A, pt):
    zs = [z for z in A.ZONES if any(r[0] - 0.06 <= pt[0] <= r[2] + 0.06 and r[1] - 0.06 <= pt[1] <= r[3] + 0.06 for r in z.get("rects", []))]
    return min(zs, key=lambda z: z["level"]) if zs else None


def _first_in(pts, rc, step=0.005):
    """Μήκος κατά μήκος της όδευσης ως το πρώτο σημείο μέσα στο ορθογώνιο rc (None αν δεν το διασχίζει)."""
    L = 0.0
    for a, b in zip(pts, pts[1:]):
        d = _dd(a, b); n = max(1, int(d / step))
        for i in range(n + 1):
            q = (a[0] + (b[0] - a[0]) * i / n, a[1] + (b[1] - a[1]) * i / n)
            if rc[0] - 1e-9 <= q[0] <= rc[2] + 1e-9 and rc[1] - 1e-9 <= q[1] <= rc[3] + 1e-9:
                return L + d * i / n
        L += d
    return None


def cond_chain(ctx, rect):
    pp = [r for r in P.REG if r[0] == ctx and r[1] == "pipe" and r[2] == "cond" and r[5] not in ("open", "balcony")]
    st = [r for r in pp if CK.d_pt_poly(r[4][0], CK.rect_poly(rect)) <= 0.12]
    if len(st) != 1:
        return None
    ch = [st[0]]
    while True:
        nx = [r for r in pp if all(r is not c for c in ch) and _dd(r[4][0], ch[-1][4][-1]) < 0.02]
        if not nx:
            return ch
        ch.append(nx[0])


def cond_end(ctx, rec):
    """Πού καταλήγει η αλυσίδα: ('trap', όνομα) · ('head' | 'wye', αγωγός, πατοσίφωνο, γωνία°, απόσταση ως το πατοσίφωνο) · (None, απόσταση)."""
    e, a = rec[4][-1], rec[4][-2]
    for w in [r for r in P.REG if r[0] == ctx and r[1] == "pipe" and r[2] == "rain" and r[5] == "balcony"]:      # R26: πλευρική έξοδος σιφωνιού εξώστη
        if _dd(e, w[4][0]) <= 0.02:                # R27: πλάγια είσοδος στο ΣΩΜΑ του σιφωνιού (αρχή της πλευρικής εξόδου του)
            yd = min(RD, key=lambda k_: _dd(RD[k_], w[4][-1]))
            return ("gullybody", w, yd if _dd(RD[yd], w[4][-1]) <= 0.10 else None, CK.plen(w[4]))
        for p0, p1 in zip(w[4], w[4][1:]):
            if CK.d_pt_seg(e, p0, p1) <= 0.02 and _dd(e, p0) > 0.02:
                ub, um = (e[0] - a[0], e[1] - a[1]), (p1[0] - p0[0], p1[1] - p0[1])
                ang = math.degrees(math.acos(max(-1.0, min(1.0, (ub[0] * um[0] + ub[1] * um[1]) / (math.hypot(*ub) * math.hypot(*um))))))
                yd = min(RD, key=lambda k_: _dd(RD[k_], w[4][-1]))
                return ("gully", w, yd if _dd(RD[yd], w[4][-1]) <= 0.10 else None, ang, _dd(e, p1) + CK.plen(w[4][w[4].index(p1):]))
    traps = [r for r in P.REG if r[0] == ctx and r[1] == "trap"]
    for t in traps:
        if _cmax(e, t[4]) <= 0.08:
            return ("trap", t[5])
    best = None
    for w in [r for r in P.REG if r[0] == ctx and r[1] == "pipe" and r[2] == "waste"]:
        for i, (p0, p1) in enumerate(zip(w[4], w[4][1:])):
            d = CK.d_pt_seg(e, p0, p1)
            if best is None or d < best[0]:
                best = (d, w, i, p0, p1)
    d, w, i, p0, p1 = best
    if d > 0.05:
        return (None, d)
    ub, um = (e[0] - a[0], e[1] - a[1]), (p1[0] - p0[0], p1[1] - p0[1])
    ang = math.degrees(math.acos(max(-1.0, min(1.0, (ub[0] * um[0] + ub[1] * um[1]) / (math.hypot(*ub) * math.hypot(*um))))))
    tr = next((t for t in traps if _cmax(w[4][-1], t[4]) <= 0.16), None)
    rest = _dd(e, p1) + CK.plen(w[4][i + 1:])
    return ("head" if i == 0 and _dd(e, w[4][0]) <= 0.05 else "wye", w, tr[5] if tr else None, ang, rest)


