def riser():
    c = C
    X0, X1, H, YB = 150, 950, 84, 134
    LV = [("ΥΠΟΓΕΙΟ", "−3,00", ""), ("ΙΣΟΓΕΙΟ", "+0,45", ""), ("Α΄ ΟΡΟΦΟΣ", "+3,80", ""), ("Β΄ ΟΡΟΦΟΣ", "+6,90", ""), ("Γ΄ ΟΡΟΦΟΣ", "+10,00", ""),
          ("Δ΄ ΟΡΟΦΟΣ", "+13,10", ""), ("ΣΟΦΙΤΑ", "+16,25", "πλάκα +16,05 · γέμισμα 20 cm"), ("ΣΤΕΓΗ", "+19,12", "")]
    fy = lambda i: YB + i * H
    XS = {"ΑΠ3": 250, "ΑΠ1": 425, "ΑΠ2": 600, "ΙΣ": 690, "ΑΠ4": 790, "ΥΔ": 898}
    yc = lambda x: fy(1) - 20 - (790 - x) * 0.02          # συλλεκτήρας (κλίση προς τα αριστερά)

    def ln(pts, col, lw, dash=None, halo=True):
        c.saveState(); c.setLineJoin(1); c.setLineCap(0 if dash else 1)
        for w, cl, d in ([(lw + 1.6, (1, 1, 1), None)] if halo else []) + [(lw, col, dash)]:
            c.setStrokeColorRGB(*cl); c.setLineWidth(w); c.setDash(d or [])
            p = c.beginPath(); p.moveTo(*pts[0])
            for q in pts[1:]:
                p.lineTo(*q)
            c.drawPath(p, stroke=1, fill=0)
        c.restoreState()

    def chip(x, y, t, col, w=None):
        w = w or max(17, SW(t, "Inter-SemiBold", 5.6) + 6); h = 10.5
        c.saveState(); c.setFillColorRGB(1, 1, 1); c.setStrokeColorRGB(*col); c.setLineWidth(0.8); c.roundRect(x - w / 2, y - h / 2, w, h, 2, stroke=1, fill=1)
        c.setFont("Inter-SemiBold", 5.6); c.setFillColorRGB(*col); c.drawCentredString(x, y - 2, t); c.restoreState()

    def trp(x, y):
        a = 4.8
        c.saveState(); c.setFillColorRGB(1, 1, 1); c.setStrokeColorRGB(*WASTE); c.setLineWidth(0.9); c.rect(x - a, y - a, 2 * a, 2 * a, stroke=1, fill=1)
        c.setLineWidth(0.6); c.circle(x, y, 2.9, stroke=1, fill=0); c.line(x - 2.9, y, x + 2.9, y); c.line(x, y - 2.9, x, y + 2.9); c.restoreState()

    def group(x, yf, d, cap, wc=True, tname=None, feeds=(), solo=None):
        """Σύνδεση ορόφου στη στήλη x: WC (Φ90) πάνω, πατοσίφωνο με τους υποδοχείς του κάτω. d = +1 δεξιά / −1 αριστερά."""
        if wc:
            ln([(x, yf + 27), (x + d * 7, yf + 34), (x + d * 26, yf + 34)], SOIL, 2.0); chip(x + d * 36, yf + 34, "WC", SOIL)
        xt = x + d * 36
        if tname:
            xl = xt + d * (27 + 23 * (len(feeds) - 1)) if feeds else xt
