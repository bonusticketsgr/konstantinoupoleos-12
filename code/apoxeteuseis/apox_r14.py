def table(x, y, title, cols, rows, widths, size=6.0, rowh=13):
    C.setFont("Inter-Bold", 9); C.setFillColorRGB(*DARK); C.drawString(x, y, title)
    y -= 18; xs = [x]
    for w in widths[:-1]: xs.append(xs[-1] + w)
    for j, h in enumerate(cols):
        C.setFont("Inter-SemiBold", size); C.setFillColorRGB(*GREY); C.drawString(xs[j], y, h)
    C.setStrokeColorRGB(*DARK); C.setLineWidth(0.6); C.line(x, y - 4, x + sum(widths), y - 4)
    y -= 16
    for r in rows:
        hmax = 1
        for j, s in enumerate(r):
            words, cur, lines = str(s).split(), "", []
            for wd in words:
                t = (cur + " " + wd).strip()
                if C.stringWidth(t, "Inter", size) > widths[j] - 8 and cur: lines.append(cur); cur = wd
                else: cur = t
            lines.append(cur)
            for k, ln in enumerate(lines):
                C.setFont("Inter-Bold" if j == 0 else "Inter", size); C.setFillColorRGB(*((0.75, 0.40, 0.0) if j == len(r) - 1 and len(cols) == 4 else DARK))
                C.drawString(xs[j], y - k * (size + 1.6), ln)
            hmax = max(hmax, len(lines))
        ly = y - (hmax - 1) * (size + 1.6) - 4.5
        C.setStrokeColorRGB(0.82, 0.82, 0.82); C.setLineWidth(0.3); C.line(x, ly, x + sum(widths), ly)
        y = ly - size - 5
    return y

