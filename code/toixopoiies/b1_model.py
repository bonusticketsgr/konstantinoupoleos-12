def _arc_lengths(walls):
    for w in walls:
        if not is_rect(w["pts"]) and len(w["pts"]) > 8:
            x0, y0, x1, y1 = bbox(w["pts"])
            # τεταρτοκύκλιο: μέσος άξονας ≈ (R_out + R_in)/2 · π/2
            r_out = max(x1 - x0, y1 - y0); th = TYPES[w["type"]]["thick"]
            w["arc_len"] = round((r_out - th / 2) * math.pi / 2, 3)

