# ---------------------------------------------------------------- βοηθητικά
def bbox(pts):
    xs = [p[0] for p in pts]; ys = [p[1] for p in pts]
    return (min(xs), min(ys), max(xs), max(ys))

def rect(x0, y0, x1, y1):
    return [[x0, y0], [x1, y0], [x1, y1], [x0, y1]]

def near(a, b, tol=0.012):
    return abs(a - b) <= tol

def is_rect(pts):
    return len(pts) == 4 or (len(pts) == 5 and pts[0] == pts[-1])

def wall_length(w):
    """Μήκος στον άξονα: η μεγάλη διάσταση του bbox (καμπύλα τμήματα: μήκος τόξου)."""
    if w.get("arc_len"):
        return w["arc_len"]
    x0, y0, x1, y1 = bbox(w["pts"])
    return max(x1 - x0, y1 - y0)

