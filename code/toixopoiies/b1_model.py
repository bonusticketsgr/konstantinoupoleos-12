def _apply_r15(walls, etics, wins):
    out = []
    for w in walls:
        b = bbox(w["pts"]); t = w["type"]
        # 2. Τ3-06 (επένδυση δίπλα στη ντουλάπα Υπν.2) καταργείται
        if t == "T3" and near(b[0], 9.366, 0.02) and near(b[1], 1.35, 0.02):
            continue
        # 2. Τ1-05: 0,50–1,45 → 0,50–1,35 (περασιά με τη ντουλάπα)
        if t == "T1" and near(b[0], 9.45, 0.02) and near(b[1], 0.50, 0.02) and near(b[3], 1.45, 0.02):
            w = {"type": t, "pts": rect(b[0], b[1], b[2], 1.35)}
        # 2. Τ1-06 και Τ3-07: 2,45–3,00 → 2,35–3,00
        if t in ("T1", "T3") and near(b[1], 2.45, 0.02) and near(b[3], 3.00, 0.02) and b[0] > 9.3:
            w = {"type": t, "pts": rect(b[0], 2.35, b[2], b[3])}
        # 3. Τ2-05 (επιστροφή ντουλάπας πλυντηρίου, x 5,35–5,45) → Τ2N
        if t == "T2" and near(b[0], 5.35, 0.02) and near(b[1], 4.35, 0.02):
            w = {"type": "T2N", "pts": w["pts"]}
        out.append(w)
    # 1. Υπν.1: κουτί γυψοσανίδας Τ2 x 4,30–4,40 από τον βόρειο τοίχο έως τη ντουλάπα (y 0,165–0,80)
    #    ώστε η πρόσοψη της ντουλάπας (x 4,30) να είναι περασιά με τοίχο· το κενό πίσω του κλείνει.
    out.append({"type": "T2", "pts": rect(4.30, 0.165, 4.40, 0.80), "id": "T2-09", "note": "κουτί – χωνευτή ντουλάπα Υπν.1"})
    # ETICS / WIN: μετατόπιση W2.06 κατά 10 cm βόρεια
    for poly in etics:
        for p in poly:
            if p[0] > 9.6:
                if near(p[1], 1.45, 0.02): p[1] = 1.35
                if near(p[1], 2.45, 0.02): p[1] = 2.35
    for poly in wins:
        b = bbox(poly)
        if near(b[0], 9.45, 0.02) and near(b[1], 1.45, 0.02):
            poly[:] = rect(b[0], 1.35, b[2], 2.35)
    return out

def _assign_ids(walls):
    """Αρίθμηση: όπου υπάρχει ετικέτα στο R14 (κείμενο Txx-nn) κρατιέται· τα υπόλοιπα παίρνουν τους
    ελεύθερους αριθμούς του είδους με σειρά ανάγνωσης (y, x)."""
    labels = []
    for t in GEOM["texts"]:
        s = t["text"].strip()
        if len(s) >= 5 and s[0] == "T" and "-" in s and s[1].isdigit():
            x0, y0, x1, y1 = t["bbox"]
            labels.append((s, ((x0 + x1) / 2, (y0 + y1) / 2)))
    for w in walls:
        w.setdefault("id", None)
    for s, (cx, cy) in labels:
        typ = s.split("-")[0]
        cands = [w for w in walls if w["type"] == typ and w["id"] is None]
        best, bd = None, 9e9
        for w in cands:
            x0, y0, x1, y1 = bbox(w["pts"])
            dx = max(x0 - cx, 0, cx - x1); dy = max(y0 - cy, 0, cy - y1)
            d = math.hypot(dx, dy)
            if d < bd: best, bd = w, d
        if best is not None and bd < 0.15:
            best["id"] = s
    reserved = {"T2": {5}, "T3": {6}}   # R14 αριθμοί που άλλαξαν είδος / καταργήθηκαν – δεν ξαναδίνονται
    for typ in TYPE_ORDER:
        used = {int(w["id"].split("-")[1]) for w in walls if w["type"] == typ and w["id"]} | reserved.get(typ, set())
        free = [n for n in range(1, 40) if n not in used]
        rest = sorted([w for w in walls if w["type"] == typ and w["id"] is None],
                      key=lambda w: (round(bbox(w["pts"])[1], 1), bbox(w["pts"])[0]))
        for w in rest:
            w["id"] = "%s-%02d" % (typ, free.pop(0))
    return walls

def _arc_lengths(walls):
    for w in walls:
        if not is_rect(w["pts"]) and len(w["pts"]) > 8:
            x0, y0, x1, y1 = bbox(w["pts"])
            # τεταρτοκύκλιο: μέσος άξονας ≈ (R_out + R_in)/2 · π/2
            r_out = max(x1 - x0, y1 - y0); th = TYPES[w["type"]]["thick"]
            w["arc_len"] = round((r_out - th / 2) * math.pi / 2, 3)

def _merge_slivers(walls):
    out = []
    for w in walls:
        b = bbox(w["pts"])
        if w["type"] == "T9" and (b[3] - b[1]) < 0.05 and (b[2] - b[0]) < 0.05:
            continue   # σφήνα 0,03 m του R14 (Τ9 στην Κ2) – περιλαμβάνεται στον Τ9-02
        out.append(w)
    return out

