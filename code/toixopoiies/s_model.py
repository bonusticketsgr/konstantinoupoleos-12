def WARC(t, i, cx, cy, r_out, r_in, a0, a1):
    """Καμπύλος τοίχος (τεταρτοκύκλιο): εξωτερικό τόξο a0→a1, εσωτερικό πίσω."""
    pts = _arc(cx, cy, r_out, a0, a1) + _arc(cx, cy, r_in, a1, a0)
    return {"type": t, "id": "%s-%02d" % (t, i), "pts": [list(p) for p in pts],
            "arc_len": round((r_out + r_in) / 2 * math.radians(abs(a1 - a0)), 3)}

