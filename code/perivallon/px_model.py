def fill_rows():
    """Πίνακας μπαζωμάτων: ζώνη, εμβαδόν, πλάκα, κορυφή μπαζώματος, πάχος, τελικό, όγκος."""
    rows = []
    for z in ZONES:
        if z["kind"] in ("pav", "pocket"):
            th = z["fill_top"] - z["slab"]
            a = area(z["poly"])
            rows.append(dict(id=z["id"], name=z["name"], area=a, slab=z["slab"], fill_top=z["fill_top"], thick=th, final=z["final"],
                             vol=a * th, pocket=(z["kind"] == "pocket")))
        elif z["kind"] == "stair":
            s = [s for s in STAIRS if s["id"] in z["name"]][0]
            a = area(z["poly"])
            # μέσο πάχος μπαζώματος κάτω από τα σκαλιά: από την πλάκα ως τη μέση στάθμη των πατημάτων μείον επίστρωση 10
            mean_tread = sum(s["levels"][:-1]) / max(1, len(s["levels"]) - 1)
            th = mean_tread - PAV - z["slab"]
            rows.append(dict(id=z["id"], name=z["name"], area=a, slab=z["slab"], fill_top=None, thick=th, final=None, vol=a * th, pocket=False))
    return rows


def soil_rows():
    rows = []
    for z in ZONES:
        if z["kind"] in ("soil", "gravel"):
            a = area(z["poly"])
            th = (z["final"] - z["slab"]) if z["slab"] is not None else None
            rows.append(dict(id=z["id"], name=z["name"], area=a, slab=z["slab"], top=z["final"], thick=th, note=z.get("note", "")))
    return rows


def wall_top_at(w, y):
    t = w["top"]
    if isinstance(t, list):
        for y0, y1, lv in t:
            if y0 - 1e-6 <= y <= y1 + 1e-6:
                return lv
        return t[-1][2]
    return t


def wall_rows():
    """Πίνακας τοιχίων: id, θέση, μήκος, πάχος, έδραση, κορυφή, ύψος."""
    rows = []
    for w in WALLS:
        xs = [p[0] for p in w["poly"]]; ys = [p[1] for p in w["poly"]]
        if w["id"] == "ΤΧ-02":
            L, th = math.pi / 2 * 3.89, 0.22
        else:
            L = max(max(xs) - min(xs), max(ys) - min(ys)); th = min(max(xs) - min(xs), max(ys) - min(ys))
        top = w["top"]
        if isinstance(top, list):
            top_txt = " / ".join(("%+.2f" % lv).replace(".", ",") for _, _, lv in top)
            hmax = max(lv for _, _, lv in top) - (w["base"] if w["base"] is not None else 0)
        else:
            top_txt = ("%+.2f" % top).replace(".", ",")
            hmax = top - (w["base"] if w["base"] is not None else 0)
        rows.append(dict(id=w["id"], kind=w["kind"], L=L, th=th, base=w["base"], top=top_txt, h=hmax, note=w["note"],
                         x=(min(xs), max(xs)), y=(min(ys), max(ys))))
    return rows
