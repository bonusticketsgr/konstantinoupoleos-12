    for (lo, hi), (face, lab), names in (((x0, x1), h["rx"], ("ανατ.", "δυτ.")), ((y0, y1), h["ry"], ("νότια", "βόρ."))):
        d, e = edge_d(lo, hi, face); lab = lab.replace("παρειά", "παρ.")
        if abs(d) < 1e-6 and h.get("xalign") and names[0] == "ανατ.": out.append("ανατ. ακμή στην ευθεία της %s" % lab)
        elif abs(d) < 1e-6: out.append("κολλητά στη %s" % lab)
        elif lo < face < hi: out.append("%s ακμή %s %s της %s" % ("δυτ." if names[0] == "ανατ." else "βόρ.", cm(d), names[1], lab))
        else: out.append("%s %s της %s" % (cm(d), names[0] if d > 0 else names[1], lab))
    return " · ".join(out)


