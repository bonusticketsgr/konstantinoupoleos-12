def cm(z):
    """Απόσταση για το σχέδιο: cm ως 99 cm (π.χ. 31,5), αλλιώς m (π.χ. 1,485 m)."""
    z = abs(z)
    if z < 0.995:
        t = "%.1f" % (z * 100)
        return (t[:-2] if t.endswith(".0") else t).replace(".", ",")
    return ("%.3f" % z).rstrip("0").rstrip(".").replace(".", ",") + " m"


def edge_d(lo, hi, face):
    """Απόσταση παρειάς σκυροδέματος → πλησιέστερη ακμή του κουτιού (lo–hi) και η ακμή αυτή. 0 = ΚΟΛΛΗΤΑ."""
    return (lo - face, lo) if face <= lo + 1e-9 else (hi - face, hi) if face >= hi - 1e-9 else (lo - face, lo)


def hole_pos(h):
    """Κείμενο θέσης (όπως στον πίνακα του τεύχους αποχετεύσεων): από τις δύο παρειές αναφοράς ως τις ακμές του κουτιού, σε cm."""
