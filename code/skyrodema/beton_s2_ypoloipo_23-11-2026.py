ZONES = {}
def slab(z, name, x0, y0, x1, y1, h):
    ZONES.setdefault(z, []).append((name, "πλάκα", (x0, y0, x1, y1), (x1-x0)*(y1-y0), h, (x1-x0)*(y1-y0)*h))
def beam(z, name, b, hh, L, rect=None):
    ZONES.setdefault(z, []).append((name, "δοκός", rect, None, None, b*hh*L))
def lump(z, name, v):
    ZONES.setdefault(z, []).append((name, "λοιπά", None, None, None, v))

